/** قائمة مسطّحة، والخيارات مخلوطة بترتيب ثابت (فلا تكون الإجابة الصحيحة دائماً الأولى) */
function bankQuestions() {
  const out = [];
  let seed = 7;
  const rnd = () => { seed = (seed * 16807) % 2147483647; return seed / 2147483647; };
  for (const [subject, lessons] of Object.entries(BANK)) {
    for (const [lesson, qs] of Object.entries(lessons)) {
      for (const [q, choices] of qs) {
        const order = choices.map((c, i) => ({ c, i, k: rnd() })).sort((a, b) => a.k - b.k);
        out.push({ subject, lesson, q, choices: order.map((o) => o.c), answer: order.findIndex((o) => o.i === 0) });
      }
    }
  }
  return out;
}

